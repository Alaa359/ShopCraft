// Traduit une clé pour une langue donnée (repli français)
export function translate(lang, key) {
  return STRINGS[lang]?.[key] ?? STRINGS.fr[key] ?? key;
}

// Hook pratique : { lang, t } où t(clé) traduit dans la langue active
export function useT() {
  const lang = useSettingsStore((state) => state.lang);
  return { lang, t: (key) => translate(lang, key) };
}